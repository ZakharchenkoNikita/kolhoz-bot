/**
 * Базовый класс для всех парсеров кооператива.
 * Содержит общую логику загрузки страниц и стандартизированного логирования.
 */
class BaseParser {
    constructor(client, db, username) {
        this.client   = client;
        this.db       = db;
        this.username = username;
    }

    // ==========================================
    // 🔧 ОБЩИЕ УТИЛИТЫ
    // ==========================================

    /** Единый формат логов для всех парсеров */
    log(emoji, message) {
        console.log(`${emoji} [${this.username}] ${message}`);
    }

    /** Универсальный загрузчик HTML с базовой обработкой ошибок */
    async fetchPage(url) {
        const $ = await this.client.fetchHtml(url);
        if (!$) {
            this.log('❌', `Ошибка загрузки страницы: ${url}`);
            return null;
        }
        return $;
    }

    // ==========================================
    // 📄 КОНТРАКТ ДЛЯ НАСЛЕДНИКОВ
    // ==========================================

    /**
     * Этот метод ОБЯЗАН быть переопределен в дочерних классах.
     * @param {object} $ - Объект Cheerio
     */
    _parsePage($) {
        throw new Error('Метод _parsePage() должен быть реализован в классе-наследнике');
    }

    /** Главный метод запуска (может быть переопределен, если нужна пагинация) */
    async scan() {
        throw new Error('Метод scan() должен быть реализован в классе-наследнике');
    }
}

module.exports = BaseParser;